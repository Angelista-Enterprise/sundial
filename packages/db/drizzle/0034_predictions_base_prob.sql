-- K0.3: the fair opponent, stored beside the bet it opposes.
--
-- `skillVsConstant` on the Calibration card scores a forecaster against a
-- constant at the target's own base rate — computed with HINDSIGHT over the
-- same bets it scores. That is an oracle, and the card says so on its face.
-- The offline harness measures the honest version and the gap is real: for
-- `project-touched`, +12.3% against the oracle constant and +14.1% against a
-- past-only running mean. The live table could not compute the second, because
-- nothing stored what the base rate was at the time.
--
-- `base_prob` is the target's rate over every resolution BEFORE this one, read
-- off the calibration entry the resolving rule is about to bump — so it costs
-- no new state and cannot disagree with the tally beside it.
--
-- Nullable, twice over: a target's FIRST resolution has no past to average,
-- and every row written before this column has none either. A reader must draw
-- a missing baseline as "no opponent", never as zero — a zero baseline would
-- hand every forecaster an infinitely easy opponent and publish a skill figure
-- that means nothing.
ALTER TABLE `predictions` ADD `base_prob` real;
